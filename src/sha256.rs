//! A small, dependency-free SHA-256.
//!
//! Claude Code namespaces its Keychain item by appending the first eight hex
//! characters of `sha256($CLAUDE_CONFIG_DIR)` to the service name, so
//! `ccswitch` has to compute the same digest to address the same item. That is
//! the only reason this exists — it is a naming hash, not a security
//! primitive, and the repo's dependency budget (see `AGENTS.md`) does not
//! stretch to the `sha2` crate and its six transitive dependencies for one
//! eight-character string.
//!
//! Implemented straight from FIPS 180-4 and checked against the standard test
//! vectors plus the multi-block and length-edge cases.

